def add(number_1: int | float , number_2: int | float)-> float:
    """

    :param number_1: First inputted number
    :param number_2: Second inputted number
    :return: The sum of the 2 values
    """
    return number_1 + number_2

def subtract(number_1: int | float , number_2: int | float)-> float:
    """

    :param number_1: First inputted number
    :param number_2: Second inputted number
    :return: The difference of the 2 values
    """
    return number_1 - number_2

def multiply(number_1: int | float , number_2: int | float)-> float:
    """

    :param number_1: First inputted number
    :param number_2: Second inputted number
    :return: The product of the 2 values
    """
    return number_1 * number_2

def divide(number_1: int | float , number_2: int | float)-> float:
    """

    :param number_1: First inputted number
    :param number_2: Second inputted number
    :return: The quotient of the 2 values
    """
    return number_1 / number_2